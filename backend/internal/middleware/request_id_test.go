package middleware

import (
	"net/http"
	"regexp"
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestRequestID_WithClientProvidedID(t *testing.T) {
	clientID := "0196a3b2c4d50000a1b2c3d4e5f67890"
	c, w := buildTestRequest(http.MethodGet, "/test", map[string]string{
		"X-Request-ID": clientID,
	}, nil)

	middleware := RequestID()
	middleware(c)

	requestID, exists := c.Get("request_id")
	assert.True(t, exists)
	assert.Equal(t, clientID, requestID)
	assert.Equal(t, clientID, w.Header().Get("X-Request-ID"))
}

func TestRequestID_AutoGenerated(t *testing.T) {
	c, w := buildTestRequest(http.MethodGet, "/test", nil, nil)

	middleware := RequestID()
	middleware(c)

	requestID, exists := c.Get("request_id")
	assert.True(t, exists)
	requestIDStr := requestID.(string)
	assert.Len(t, requestIDStr, 32)
	assert.Equal(t, requestIDStr, w.Header().Get("X-Request-ID"))
}

